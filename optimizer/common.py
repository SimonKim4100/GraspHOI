class TunnelGuard:
    """Penetration term for fingers that pass through the object."""

    def __init__(self, verts, faces, margin=0.002):
        self.mesh = trimesh.Trimesh(np.asarray(verts, np.float64), np.asarray(faces, np.int64), process=False)
        self.normals = np.asarray(self.mesh.face_normals, np.float64)
        self.margin = margin

    def crossings(self, P):
        """First crossing per finger: {finger: (bone, hit point, wrist-side normal)}."""
        a, b = P[:, :-1].reshape(-1, 3), P[:, 1:].reshape(-1, 3)
        d = b - a
        L = np.linalg.norm(d, axis=1)
        ok = np.nonzero(L > 1e-9)[0]
        out = {}
        if not len(ok):
            return out
        loc, iray, itri = self.mesh.ray.intersects_location(a[ok], d[ok] / L[ok, None], multiple_hits=False)
        for p, r, t in zip(loc, iray, itri):
            seg = int(ok[r])
            if np.linalg.norm(p - a[seg]) > L[seg]:
                continue                                   # hit beyond the bone
            f, k = divmod(seg, P.shape[1] - 1)
            if f not in out or k < out[f][0]:
                n = self.normals[t].copy()
                out[f] = (k, np.array(p), n if n @ (a[seg] - p) > 0 else -n)
        return out

    def loss(self, joints, sides, s=1.0):
        """Tunneling loss of camera-frame joints. Returns (loss, tunneled finger count)."""
        chains = [c for side in sides for c in FINGER_CHAINS[side]]
        if not chains:
            return joints.new_zeros(()), 0
        P = joints[torch.as_tensor(chains, device=joints.device)]           # (F, 5, 3)
        s_ = float(s)
        hits = self.crossings(P.detach().cpu().double().numpy() / s_)
        loss = joints.new_zeros(())
        for f, (k, p, n) in hits.items():
            # the joint just past the crossing
            x = P[f, k + 1:k + 2]
            dist = (x - torch.as_tensor(p * s_, dtype=x.dtype, device=x.device)) @ torch.as_tensor(
                n, dtype=x.dtype, device=x.device)
            loss = loss + (F.relu(self.margin - dist) ** 2).sum()
        return loss, len(hits)


