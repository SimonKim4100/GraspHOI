def convert_to_full_img_cam(weak_cam, bbox_height, bbox_center, img_w, img_h, focal_length):
    """Weak-perspective crop camera -> full-image camera translation."""
    # weak_cam (s, tx, ty), box size b: depth 2 f / (s b), shift 2 (box center - image center) / (s b)
    s = weak_cam[:, 0]
    depth = 2. * focal_length / (bbox_height * s)
    dx = 2. * (bbox_center[:, 0] - img_w / 2.) / (s * bbox_height)
    dy = 2. * (bbox_center[:, 1] - img_h / 2.) / (s * bbox_height)
    return torch.stack([weak_cam[:, 1] + dx, weak_cam[:, 2] + dy, depth], dim=-1)


def run_body_model(body_model, params, pred_cam, batch):
    """SMPL/SMPL-H forward pass. Returns (vertices, joints, camera translation)."""
    out = body_model(**{name: p.float() for name, p in params.items()})
    h, w = batch['img_size'][0]
    trans = convert_to_full_img_cam(pred_cam, batch['box_size'], batch['box_center'], w, h,
                                    batch['cam_int'][:, 0, 0])
    return out.vertices, out.joints, trans


def hard_inside_mask(points_2d: torch.Tensor, mask01: torch.Tensor):
    """(B, N) bool: points (B, N, 2) inside the (H, W) bool mask."""
    B, N, _ = points_2d.shape
    H, W = mask01.shape
    x = points_2d[..., 0].round().long()
    y = points_2d[..., 1].round().long()
    valid = (x >= 0) & (x < W) & (y >= 0) & (y < H)
    x_safe = x.clamp(0, W - 1)
    y_safe = y.clamp(0, H - 1)
    flat_idx = y_safe * W + x_safe
    mask_flat = mask01.view(1, -1).expand(B, -1)
    vals = mask_flat.gather(1, flat_idx.view(B, -1))
    return vals & valid


def select_contact_vertices(output_verts, output_cam_trans, fl_0, img_w, img_h,
                            left_verts_idx, right_verts_idx, object_mask,
                            left_enabled=True, right_enabled=True):
    """Hand vertices projecting inside the object mask, per batch item."""
    device = output_verts.device
    B = output_verts.shape[0]
    verts_2d = project_joints_to_2d(output_verts, output_cam_trans, fl_0, img_w, img_h)

    out = {"left_idx_in": [], "right_idx_in": []}

    if left_enabled and len(left_verts_idx) > 0:
        left_idx_t = torch.tensor(left_verts_idx, dtype=torch.long, device=device)
        left_in = hard_inside_mask(verts_2d[:, left_idx_t, :], object_mask)
        for b in range(B):
            out["left_idx_in"].append(left_idx_t[left_in[b]].detach())

    if right_enabled and len(right_verts_idx) > 0:
        right_idx_t = torch.tensor(right_verts_idx, dtype=torch.long, device=device)
        right_in = hard_inside_mask(verts_2d[:, right_idx_t, :], object_mask)
        for b in range(B):
            out["right_idx_in"].append(right_idx_t[right_in[b]].detach())

    return out


def first_or_empty(lst, device):
    """First tensor of lst, or an empty long tensor."""
    if lst and isinstance(lst[0], torch.Tensor):
        return lst[0]
    return torch.empty(0, dtype=torch.long, device=device)


def geodesic_angle(R: torch.Tensor, R0: torch.Tensor, eps: float = 1e-6) -> torch.Tensor:
    """Rotation angle (rad) of R0^T R."""
    R_rel = R0.transpose(-1, -2) @ R
    tr = R_rel.diagonal(offset=0, dim1=-2, dim2=-1).sum(-1)
    # eps keeps the acos gradient finite
    cos = ((tr - 1.0) * 0.5).clamp(-1.0 + eps, 1.0 - eps)
    return torch.acos(cos)


def angle_barrier(angles: torch.Tensor, thresh_rad: torch.Tensor, power: int) -> torch.Tensor:
    """Angular barrier ([angle - thresh]_+ / thresh) ** power."""
    over = F.relu(angles - thresh_rad)
    return (over / thresh_rad).pow(power)


def reg_distance(R, R0):
    """Squared geodesic angle between R and R0."""
    ang = geodesic_angle(R, R0)
    return ang * ang


def project_to_image(verts3d, focal_length, img_w, img_h, pp=None):
    """Project camera-frame points (N, 3) to pixels (N, 2)."""
    fx, fy = focal_length
    cx, cy = (img_w / 2.0, img_h / 2.0) if pp is None else pp
    x, y, z = verts3d[:, 0], verts3d[:, 1], verts3d[:, 2]
    u = fx * x / z + cx
    v = fy * y / z + cy
    return torch.stack([u, v], dim=1)


def get_2d_bbox_from_verts(verts3d, focal_length, img_w, img_h, pp=None):
    """(center, size) of the projected vertices' 2D box."""
    verts2d = project_to_image(verts3d, focal_length, img_w, img_h, pp=pp)
    min_xy = torch.min(verts2d, dim=0)[0]
    max_xy = torch.max(verts2d, dim=0)[0]
    center = (min_xy + max_xy) / 2.0
    size = max_xy - min_xy
    return center, size


