def arm_limit_loss(arm_rots, init_Rs, limits):
    """Squared excess of each arm joint's angle from its start (limits in rad)."""
    loss = 0.0
    for rot, R0 in zip(arm_rots, init_Rs):
        loss = loss + (F.relu(geodesic_angle(axis_angle_to_matrix(rot), R0) - limits) ** 2).sum()
    return loss


def anchor_drift_loss(joints_2d, anchor_2d, joints_cam, idx, focal, tol):
    """Squared drift from the 2D anchors beyond tol (m at each joint's depth)."""
    d = (joints_2d[0, idx] - anchor_2d[0, idx]).norm(dim=-1) * joints_cam[0, idx, 2].detach() / focal
    return (F.relu(d - tol) ** 2).sum()


def split_wrist_twist(body_pose, axes, frac=0.5, min_deg=60.0):
    """Move frac of a large wrist twist to the elbow, in place. Returns {wrist: twist deg}."""
    out = {}
    for w, (e, a) in axes.items():
        a = torch.as_tensor(a, dtype=body_pose.dtype, device=body_pose.device)
        q = matrix_to_quaternion(body_pose[:, w])                     # (B, 4) w x y z
        theta = 2 * torch.atan2(q[:, 1:] @ a, q[:, 0])
        theta = (theta + torch.pi) % (2 * torch.pi) - torch.pi
        mv = torch.where(theta.abs() > np.radians(min_deg), frac * theta, torch.zeros_like(theta))
        T = axis_angle_to_matrix(mv[:, None] * a[None])
        body_pose[:, e] = body_pose[:, e] @ T
        body_pose[:, w] = T.transpose(-1, -2) @ body_pose[:, w]
        out[w] = float(np.degrees(theta[0].item()))
    return out


